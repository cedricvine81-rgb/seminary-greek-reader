// Full multi-section summaries for each work in the Texts library, surfaced in the "Summary"
// popover (and the Contents-only popover) beside an open text's title (see TextsReader). Where a
// work already has a vetted entry in backgrounds-summaries.ts (the Second Temple student guide),
// that entry's sections are reused; every other work is authored below.
//
// IMPORTANT: the authored entries here are AI-drafted at an introductory level, reflecting
// mainstream scholarly consensus but NOT verified against specific peer-reviewed sources. They are
// flagged `aiDrafted` so the popover shows a caveat, and they should be checked by a specialist
// before being relied on. Corrections welcome. Each has five sections: Authorship, Historical
// Context, Contents, Theological Significance, and Relationship to New Testament.
import { BACKGROUND_SUMMARIES } from './backgrounds-summaries'
import type { CatalogWork } from './texts-catalog'

export interface TextSummarySection { heading: string; body: string }
/** A work's summary as an ordered list of sections (the "Summary" popover renders all of them;
 *  the "Contents" popover renders just the Contents section). `aiDrafted` marks the authored
 *  entries below, which reflect mainstream scholarship but are not verified against sources — the
 *  popover shows a caveat for these; the reused Backgrounds summaries are not so flagged. */
export interface TextSummary { sections: TextSummarySection[]; aiDrafted?: boolean }

const norm = (s: string) => s.toLowerCase().replace(/[^a-z0-9]/g, '')

// Index the vetted Backgrounds summaries by normalized title so a Texts work can show that work's
// full multi-section summary (Authorship, Historical Context, Contents, Theological Significance,
// Relationship to New Testament) when the names match.
const _bgByName = new Map<string, TextSummarySection[]>()
for (const cat of BACKGROUND_SUMMARIES) {
  for (const w of cat.works) {
    _bgByName.set(norm(w.title), w.sections.map(s => ({ heading: s.heading, body: s.body })))
  }
}

/** Full summary sections for an open Texts work, or null if none is known. Works with a vetted
 *  Backgrounds summary get its full section set; the rest get the authored sections below. */
export function getTextSummary(work: Pick<CatalogWork, 'id' | 'name'>): TextSummary | null {
  const bg = _bgByName.get(norm(work.name)) ?? _bgByName.get(norm(work.name.replace(/\s*\(.*\)$/, '')))
  if (bg && bg.length) return { sections: bg }
  // A work split across several catalog entries (Herodotus' nine books, Quintilian's twelve,
  // Eusebius' ten) shares one summary: fall back to the id with its trailing book number
  // stripped, so "herodotus-histories-7" finds "herodotus-histories". A book that genuinely
  // warrants its own entry can still have one — an exact-id match always wins.
  const authored = TEXT_SUMMARIES[work.id] ?? TEXT_SUMMARIES[work.id.replace(/-\d+$/, '')]
  if (authored) return { sections: authored.sections, aiDrafted: true }
  return null
}

interface AuthoredSummary { sections: TextSummarySection[] }

// Helper to keep the authored entries compact: five standard sections in order.
function S(authorship: string, context: string, contents: string, significance: string, nt: string): AuthoredSummary {
  return {
    sections: [
      { heading: 'Authorship', body: authorship },
      { heading: 'Historical Context', body: context },
      { heading: 'Contents', body: contents },
      { heading: 'Theological Significance', body: significance },
      { heading: 'Relationship to New Testament', body: nt },
    ],
  }
}

