/**
 * Localized display names for the /texts library catalogue — the category list, the author
 * headings, and the work titles shown in the Texts menus.
 *
 * WHY A CATALOGUE RATHER THAN t() KEYS: identical reasoning to book-names.ts, plus one thing
 * message keys cannot express. The menu derives its MIDDLE level by parsing `CatalogWork.name`
 * — `groupWorksByAuthor` splits "Author, Title" on ", " and `workTitleWithoutAuthor` strips the
 * rabbinic siglum ("b. Berakhot"). A translated string dropped into `name` would break that
 * parse, so author and title are localized as SEPARATE entries here and the parse keeps running
 * on the untouched English.
 *
 * THE ONE RULE, exactly as in book-names.ts: **localize the DISPLAY, never the STORED string.**
 * `CatalogWork.name` is also what a reader copies — `citeFor` in TextsReader builds
 * `${work.name} ${row.ref}`, and `refLabelFor` builds the Josephus/prose reference the same way.
 * Those must stay English, because a citation pasted into a paper has to match how the work is
 * cited in the literature and how this app's own note keys are stored. Nothing here is reachable
 * from either function; every export below runs at render time only.
 *
 * A missing entry falls back to the English the caller already had — the never-mislead rule the
 * fingerprinted content catalogues use, so a partly covered locale degrades to English rather
 * than to a work id. `npm run i18n:texts` reports what is not yet covered.
 *
 * THE SEPTUAGINT AND APOCRYPHA ARE NOT REPEATED HERE. Those works carry an `osisId` and their
 * Spanish already lives in book-names.ts; `textWorkTitle` delegates when given one, so Génesis
 * is defined once. Do not add them below — a second copy is a second thing to drift.
 */

interface TextNames {
  /** Category id (TEXT_CATEGORIES[].id) → display label. */
  categories: Record<string, string>
  /** Explicit `CatalogWork.group` (the rabbinic corpora) → display label. */
  groups: Record<string, string>
  /** Author heading as `groupWorksByAuthor` derives it → display label. */
  authors: Record<string, string>
  /** Work id → title WITHOUT the author prefix, matching `workTitleWithoutAuthor`'s output. */
  works: Record<string, string>
}

