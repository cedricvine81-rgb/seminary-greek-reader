const BY_LOCALE: Partial<Record<Locale, TextNames>> = { es: ES }

/** Whether this locale has any catalogue coverage at all. */
export function hasTextNames(locale: string): boolean {
  return !!BY_LOCALE[locale as Locale]
}

/** Category label ("Apócrifos"), falling back to the English the caller already had. */
export function textCategoryLabel(id: string, locale: string, english: string): string {
  return BY_LOCALE[locale as Locale]?.categories[id] ?? english
}

/**
 * Rabbinic corpus label ("Talmud de Jerusalén").
 *
 * `english` defaults to the group name itself, which is what every render site wants. It is a
 * parameter only so the coverage check can pass a sentinel and tell an ABSENT key apart from one
 * whose Spanish is legitimately identical (Tosefta).
 */
export function textGroupLabel(group: string, locale: string, english = group): string {
  return BY_LOCALE[locale as Locale]?.groups[group] ?? english
}

/** Author heading ("Platón"). `english` exists for the coverage check; see textGroupLabel. */
export function textAuthorLabel(author: string, locale: string, english = author): string {
  return BY_LOCALE[locale as Locale]?.authors[author] ?? english
}

/**
 * Work title as the menus show it — WITHOUT the author prefix, so it matches what
 * `workTitleWithoutAuthor` returns for the English.
 *
 * `osisId` delegates to book-names.ts, which is why the Septuagint and the Apocrypha need no
 * entries here. `english` is the already-computed English title and is the fallback.
 */
export function textWorkTitle(workId: string, locale: string, english: string,
                              osisId?: string): string {
  const hit = BY_LOCALE[locale as Locale]?.works[workId]
  if (hit) return hit
  if (osisId) return bookName(osisId, locale, english)
  return english
}
