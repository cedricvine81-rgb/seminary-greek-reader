-- ============================================================================
--  What the Swete swap breaks in user data.  Read-only: nothing here writes.
--  Run in the Supabase SQL editor.  Postgres, so identifiers stay double-quoted.
--  Run the CREATE TEMP VIEW first, then each SELECT on its own — the editor shows
--  only the last result set when several are submitted together.  The temp views
--  live for the session, so create them once.
--
--  Three separate problems, in the order they matter:
--    1. Highlights  — character offsets into a verse whose text changed.  Dead.
--    2. Verse notes — anchored to a verse id that no longer exists.  Orphaned.
--    3. The Odes    — anchor still exists but now names a DIFFERENT canticle.
--       This is the nasty one: nothing errors, the note just sits on the wrong text.
-- ============================================================================

-- The books of our Septuagint.  The NT shares no osisIds with it, and the Hebrew
-- reader writes layer 'he', so layer = 'grc' plus this list is exactly the Greek
-- Old Testament and nothing else.
--
-- 'Eccl' is in this list even though it is no longer in books.json: Swete has no
-- Ecclesiastes, so we dropped the book — but the rows people made against it are
-- still in the database, and they are the most thoroughly broken of the lot.
-- Reading the list off the current books.json would silently skip them.
CREATE TEMP VIEW lxx_books(book) AS
SELECT unnest(ARRAY['Gen','Exod','Lev','Num','Deut','JoshB','JudgB','Ruth','1Sam','2Sam','1Kgs','2Kgs','1Chr','2Chr','Ezra','Neh','1Esd','Tob','Jdt','EsthGr','Job','Ps','PsSol','Prov','Song','Wis','Sir','Isa','Jer','Lam','EpJer','Bar','Sus','Ezek','DanLXX','Bel','Hos','Joel','Amos','Obad','Jonah','Mic','Nah','Hab','Zeph','Hag','Zech','Mal','1Macc','2Macc','3Macc','4Macc','Odes',
  'Eccl']);


-- ─── 1. HIGHLIGHTS ──────────────────────────────────────────────────────────
-- 27,937 of 28,861 verses changed their Greek text, so treat every one of these
-- as invalid unless you want to verify the 28 that did not.  THIS IS THE NUMBER
-- THAT DECIDES whether to build a migration or simply drop and notify.
SELECT count(*)                        AS highlight_rows,
       count(DISTINCT "userId")        AS users_affected,
       count(DISTINCT "book")          AS books_touched
FROM "Highlight"
WHERE "layer" = 'grc'
  AND "book" IN (SELECT book FROM lxx_books);

-- Same thing per book, worst first.
SELECT h."book", count(*) AS n_rows, count(DISTINCT h."userId") AS users
FROM "Highlight" h
WHERE h."layer" = 'grc'
  AND h."book" IN (SELECT book FROM lxx_books)
GROUP BY h."book"
ORDER BY n_rows DESC;

-- Who to notify, and how much each person loses.
SELECT "userId", count(*) AS n_rows
FROM "Highlight"
WHERE "layer" = 'grc'
  AND "book" IN (SELECT book FROM lxx_books)
GROUP BY "userId"
ORDER BY n_rows DESC;

-- Sanity check: highlights on the TRANSLATION layers are untouched — Brenton did
-- not move.  This should be a healthy number and needs no action.
SELECT "layer", count(*) AS n_rows
FROM "Highlight"
WHERE "book" IN (SELECT book FROM lxx_books)
GROUP BY "layer"
ORDER BY n_rows DESC;


