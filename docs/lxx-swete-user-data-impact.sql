SELECT count(*)                 AS notes_orphaned,
       count(DISTINCT "userId") AS users_affected
FROM "VerseNote" n
JOIN lost_anchors l
  ON l.book = n."book" AND l.chapter = n."chapter" AND l.verse = n."verse";

-- Which ones, so you can tell people what they were on.
SELECT n."userId", n."book", n."chapter", n."verse",
       left(n."body", 60) AS body_start
FROM "VerseNote" n
JOIN lost_anchors l
  ON l.book = n."book" AND l.chapter = n."chapter" AND l.verse = n."verse"
ORDER BY n."book", n."chapter", n."verse";

-- A note spanning a range can straddle the gap even when its own first verse
-- survives.  Rarer, easy to miss.
SELECT count(*) AS ranged_notes_crossing_a_gap
FROM "VerseNote" n
WHERE n."verseEnd" IS NOT NULL
  AND EXISTS (SELECT 1 FROM lost_anchors l
              WHERE l.book = n."book" AND l.chapter = n."chapter"
                AND l.verse BETWEEN n."verse" AND n."verseEnd");


-- ─── 3. THE ODES — anchors that survived but changed meaning ────────────────
-- The Odes had to be renumbered so the English and Spanish line up again, which
-- means an anchor like Odes 4:1 still resolves — to Habakkuk now, where it used
-- to be Isaiah.  Every Odes anchor is suspect regardless of whether it survived,
-- so these need reading by hand, not migrating by rule.
SELECT 'note' AS kind, "userId", "book", "chapter", "verse", left("body", 60) AS detail
FROM "VerseNote" WHERE "book" = 'Odes'
UNION ALL
SELECT 'highlight', "userId", "book", "chapter", "verse", "layer"
FROM "Highlight" WHERE "book" = 'Odes'
ORDER BY 2, 4, 5;
